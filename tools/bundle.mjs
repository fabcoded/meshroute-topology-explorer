// Builds the panel's one shipped module from its sources with Rollup: no plugins, no minifying, comments kept, so
// the file stays readable and Home Assistant serves one request instead of about 100 (issue #16, spec 10).
// Usage: npm run bundle (writes the file)   node tools/bundle.mjs --check (exit 1 if the committed file is stale;
// pre-commit hook bundle-fresh). Rollup is a pinned development dependency; nothing is built at install time.
import { readFileSync, writeFileSync } from "node:fs";
import { relative, resolve, sep } from "node:path";
import process from "node:process";
import { rollup } from "rollup";

const FRONT = "custom_components/meshroute_topology_explorer/frontend";
const INPUT = `${FRONT}/panel.js`;
const OUTPUT = `${FRONT}/dist/panel.js`;
const BANNER = "// SPDX-License-Identifier: MIT\n"
  + `// Generated by tools/bundle.mjs from ${FRONT}/ (Rollup); do not edit, run npm run bundle.`;
// The one import cycle the sources have: ui/history-links.js imports engines/index.js back and reads it only inside a
// function, so the evaluation order cannot matter. Rollup reports whichever path to it its walk meets first (through
// the Zigbee or the Thread details today), so the check accepts any cycle that starts at engines/index.js and closes
// with that back-import. Any other cycle stops the build until someone has looked at it.
const KNOWN_CYCLE_START = "engines/index.js";
const KNOWN_CYCLE_BACK = "ui/history-links.js";

/** Stops the build on a Rollup warning: a silent one could ship a module that differs from the sources the tests ran
 *  on. Only the known cycle passes (Rollup orders a cycle as the browser does, ES module evaluation order). */
function onwarn(warning) {
  const ids = (warning.ids || []).map((id) => relative(resolve(FRONT), id).split(sep).join("/"));
  const known = ids.length >= 3 && ids[0] === KNOWN_CYCLE_START && ids.at(-1) === KNOWN_CYCLE_START
    && ids.at(-2) === KNOWN_CYCLE_BACK;
  if (warning.code !== "CIRCULAR_DEPENDENCY" || !known) throw new Error(warning.message);
}

/** Line ends as in the repository (LF; .gitattributes): a CRLF checkout must not read as stale or write CRLF. */
const lf = (text) => text.replace(/\r\n/g, "\n");

/** The bundle's text with LF line ends, ending in one newline. Rollup copies each module's line ends as it reads them. */
async function build() {
  const bundle = await rollup({ input: INPUT, onwarn });
  try {
    const { output } = await bundle.generate({ format: "es", banner: BANNER });
    const code = lf(output[0].code);
    return code.endsWith("\n") ? code : `${code}\n`;
  } finally {
    await bundle.close();
  }
}

const code = await build();
if (process.argv.includes("--check")) {
  let current = null;
  try { current = lf(readFileSync(OUTPUT, "utf8")); } catch { /* missing counts as stale, reported below */ }
  if (current !== code) {
    process.stderr.write(`${OUTPUT} does not match the sources: run npm run bundle and commit the result.\n`);
    process.exit(1);
  }
} else {
  writeFileSync(OUTPUT, code);
}
